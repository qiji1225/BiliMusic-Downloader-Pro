# ---------------------------------------------------------------- cookie 处理
def normalize_cookie(raw):
    """把用户粘贴的内容统一成 `SESSDATA=xxx` 形式的 Cookie 头。

    支持三种写法：
      1. 纯 SESSDATA 值   -> 前面补上 SESSDATA=
      2. SESSDATA=xxx
      3. 整行浏览器 Cookie（含 SESSDATA=xxx; bili_jct=...; DedeUserID=...）
    """
    s = (raw or "").strip()
    if not s:
        return ""
    s = re.sub(r"^cookie\s*:\s*", "", s, flags=re.I)
    s = s.replace("\r", "").replace("\n", "")
    s = s.strip().strip('"').strip("'").strip()
    if not s:
        return ""
    if "SESSDATA" not in s.upper():
        return "SESSDATA=" + s
    parts = [p.strip() for p in s.split(";") if p.strip()]
    return "; ".join(parts)


def sessdata_of(cookie):
    m = re.search(r"SESSDATA=([^;]+)", cookie or "", re.I)
    return m.group(1).strip() if m else ""


def cookie_file(cookie):
    """把 Cookie 写成 yt-dlp 可用的 Netscape cookie 文件，返回路径或 None。"""
    try:
        if not cookie:
            return None
        os.makedirs(BUILD_DIR, exist_ok=True)
        path = os.path.join(BUILD_DIR, "bili_cookies.txt")
        exp = int(time.time()) + 400 * 86400
        lines = ["# Netscape HTTP Cookie File", "# generated by BiliMusic"]
        for pair in cookie.split(";"):
            pair = pair.strip()
            if not pair or "=" not in pair:
                continue
            k, v = pair.split("=", 1)
            k, v = k.strip(), v.strip()
            if not k:
                continue
            for domain in (".bilibili.com", ".bilivideo.com", ".biliapi.net"):
                lines.append("\t".join([domain, "TRUE", "/", "FALSE", str(exp), k, v]))
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        try:
            os.chmod(path, 0o600)
        except Exception:
            pass
        return path
    except Exception:
        return None


# ---------------------------------------------------------------- HTTP
def _get_json(url, cookie="", timeout=15):
    headers = {
        "User-Agent": UA,
        "Referer": "https://www.bilibili.com/",
        "Accept": "application/json, text/plain, */*",
        "Accept-Language": "zh-CN,zh;q=0.9",
    }
    if cookie:
        headers["Cookie"] = cookie
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read().decode("utf-8", "replace"))
    except Exception as e:
        raise BiliError("B 站接口请求失败：%s" % e)


def _check(data):
    code = data.get("code", 0)
    if code == 0:
        return data.get("data")
    msg = { -101: "Cookie 无效或已过期，请重新粘贴",
            -111: "csrf 校验失败（Cookie 不完整）",
            -400: "请求参数有误",
            -403: "访问被拒绝（可能需要重新登录）",
            -412: "被 B 站风控拦截，请稍后再试" }.get(code)
    raise BiliError(msg or ("B 站返回错误 %s：%s" % (code, data.get("message") or "")))


# ---------------------------------------------------------------- 登录 / 账号
def nav(cookie):
    """用 SESSDATA 换取账号信息。返回 dict(mid, uname, face, vip)。"""
    data = _check(_get_json(API_NAV, cookie))
    if not data.get("isLogin"):
        raise BiliError("未登录：Cookie 无效或已过期，请重新粘贴 SESSDATA")
    return {
        "mid": int(data.get("mid") or 0),
        "uname": data.get("uname") or "",
        "face": data.get("face") or "",
        "vip": bool((data.get("vipStatus") or 0) == 1 or data.get("vip_status") == 1),
        "level": int(data.get("level_info", {}).get("current_level") or 0),
    }


def folders(cookie, mid):
    data = _check(_get_json(API_FOLDERS % mid, cookie))
    items = (data or {}).get("list") or []
    out = []
    for f in items:
        out.append({
            "id": int(f.get("id") or 0),
            "title": f.get("title") or "未命名收藏夹",
            "count": int(f.get("media_count") or 0),
            "is_default": int(f.get("id") or 0) == int(mid),
        })
    return out


def folder_page(cookie, media_id, page=1, size=20):
    """读取收藏夹一页内容，只返回能下载的视频条目。"""
    data = _check(_get_json(API_FOLDER_LIST % (media_id, page, size), cookie))
    data = data or {}
    info = data.get("info") or {}
    medias = data.get("medias") or []
    items = []
    for m in medias:
        if int(m.get("attr") or 0) != 0:      # 失效 / 私密视频
            continue
        if int(m.get("type") or 0) != 2:      # 只取视频（2），音频收藏走不了视频链接
            continue
        bvid = m.get("bvid") or ""
        if not bvid:
            continue
        upper = (m.get("upper") or {}).get("name") or ""
        items.append({
            "bvid": bvid,
            "url": "https://www.bilibili.com/video/" + bvid,
            "title": m.get("title") or "",
            "cover": m.get("cover") or "",
            "duration": int(m.get("duration") or 0),
            "upper": upper,
        })
    total = int(info.get("media_count") or 0)
    return {
        "title": info.get("title") or "",
        "total": total,
        "page": page,
        "size": size,
        "has_more": page * size < total,
        "items": items,
    }
